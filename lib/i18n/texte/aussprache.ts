/** Kurzer Satz in der AUSGABEsprache, in dem die Stimme das Wort zur Probe spricht. */
const PROBESATZ: Record<string, string> = {
  de: 'Heute geht es um {wort}.',
  en: 'Today we are talking about {wort}.',
  es: 'Hoy hablamos de {wort}.',
  ca: 'Avui parlem de {wort}.',
  fr: "Aujourd'hui, on parle de {wort}.",
  it: 'Oggi parliamo di {wort}.',
  sv: 'Idag pratar vi om {wort}.',
}
export function probeSatz(sprache: string, wort: string) {
  return (PROBESATZ[sprache.slice(0, 2)] ?? PROBESATZ.en).replace('{wort}', wort)
}

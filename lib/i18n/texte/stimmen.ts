/**
 * Sätze in der AUSGABESPRACHE (nicht in der Oberflächensprache): Vorbelegung für „Mit meinem Text"
 * und der kurze Musterdialog für „Paar anhören" (A sagt Satz a, B antwortet mit Satz b). Jeweils ≤ 200 Zeichen.
 */
export const MUSTER: Record<string, { beispiel: string; a: string; b: string }> = {
  'de-DE': {
    beispiel: 'Guten Morgen! Hier sind die Nachrichten aus Ihrer Region – kurz, klar und mit einem Lächeln.',
    a: 'Guten Morgen! Heute geht es um den Wochenmarkt in Palma. Du warst doch gestern schon dort, oder?',
    b: 'Stimmt! Und ich kann dir sagen: Die Tomaten sind gerade unschlagbar. Aber der Parkplatz … na ja.',
  },
  'es-ES': {
    beispiel: '¡Buenos días! Aquí tenéis las noticias de vuestra zona: breves, claras y con una sonrisa.',
    a: '¡Buenos días! Hoy hablamos del mercado semanal de Palma. Tú estuviste ayer, ¿verdad?',
    b: '¡Sí! Y te digo una cosa: los tomates ahora mismo están buenísimos. Eso sí, aparcar… otra historia.',
  },
  'en-GB': {
    beispiel: 'Good morning! Here is the news from your area – short, clear and with a smile.',
    a: 'Good morning! Today we’re talking about the weekly market in Palma. You were there yesterday, weren’t you?',
    b: 'I was! And honestly, the tomatoes are unbeatable right now. Finding a parking space, though… not so much.',
  },
}

/** Muster für eine Ausgabesprache; unbekannte Varianten (z. B. de-AT) nehmen die Grundsprache. */
export function musterFuer(code: string) {
  return MUSTER[code] ?? Object.entries(MUSTER).find(([k]) => k.slice(0, 2) === code.slice(0, 2))?.[1] ?? MUSTER['en-GB']
}
